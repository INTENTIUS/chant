describe("chant sql drizzle, and the workspace check that keeps its file current", () => {
  let root: string;
  let cwd: string;
  let errors: string[];
  let logs: string[];

  const schema = (amount: string) =>
    'import { schema, table } from "@intentius/chant-lexicon-sql/postgres";\n' +
    "export const shop = schema`CREATE SCHEMA shop`;\n" +
    "export const orders = table`CREATE TABLE ${shop}.orders (id bigint PRIMARY KEY, " +
    `amount ${amount})\`;\n`;
  const write = (amount: string) => writeFileSync(join(root, "member", "src", "schema.ts"), schema(amount));
  const drizzle = async (...args: string[]) => {
    process.chdir(join(root, "member"));
    return runDrizzle({ verb: "drizzle", rawArgs: args });
  };

  beforeEach(() => {
    cwd = process.cwd();
    root = realpathSync(mkdtempSync(join(tmpdir(), "chant-4401-")));
    mkdirSync(join(root, "member", "src"), { recursive: true });
    symlinkSync(repoNodeModules, join(root, "member", "node_modules"), "dir");
    writeFileSync(join(root, "member", "chant.config.json"), JSON.stringify({ lexicons: ["sql"], sourceDir: "src", sql: { dialect: "postgres" } }));
    write("numeric(12,2)");
    errors = [];
    logs = [];
    vi.spyOn(console, "error").mockImplementation((m: unknown) => void errors.push(String(m)));
    vi.spyOn(console, "log").mockImplementation((m: unknown) => void logs.push(String(m)));
    process.env.NO_COLOR = "1";
  });

  afterEach(() => {
    process.chdir(cwd);
    vi.restoreAllMocks();
    delete process.env.NO_COLOR;
  });

  test("writes drizzle-schema.ts in the project, outside the source directory, and --check follows the declaration", async () => {
    expect(await drizzle()).toBe(0);
    const file = join(root, "member", "drizzle-schema.ts");
    const written = readFileSync(file, "utf8");
    expect(written).toContain('export const orders = shop.table("orders", {');
    expect(written).toContain("amount: numeric({ precision: 12, scale: 2 }),");
    expect(logs.join("\n")).toContain("wrote drizzle-schema.ts: 1 table, 0 views, 0 enums, 0 sequences");
    expect(existsSync(join(root, "member", "src", "drizzle-schema.ts"))).toBe(false);

    expect(await drizzle("--check")).toBe(0);
    write("bigint");
    expect(await drizzle("--check")).toBe(1);
    expect(errors.join("\n")).toContain("drizzle-schema.ts differs");
    expect(readFileSync(file, "utf8")).toBe(written);
  }, 30_000);

  test("--check on a missing file exits 1 and writes nothing; -o and --output write elsewhere", async () => {
    expect(await drizzle("--check")).toBe(1);
    expect(errors.join("\n")).toContain("drizzle-schema.ts does not exist");
    expect(existsSync(join(root, "member", "drizzle-schema.ts"))).toBe(false);
    expect(await drizzle("-o", "db/schema.ts")).toBe(0);
    expect(await drizzle("--check", "--output=db/schema.ts")).toBe(0);
    expect(existsSync(join(root, "member", "db", "schema.ts"))).toBe(true);
  }, 30_000);

  test("a bad argument and a ClickHouse project exit 1", async () => {
    expect(await drizzle("--bogus")).toBe(1);
    expect(await drizzle("--bigint", "string")).toBe(1);
    writeFileSync(join(root, "member", "chant.config.json"), JSON.stringify({ lexicons: ["sql"], sourceDir: "src", sql: { dialect: "clickhouse" } }));
    writeFileSync(join(root, "member", "src", "schema.ts"), 'import { database, table } from "@intentius/chant-lexicon-sql/clickhouse";\nexport const shop = database`CREATE DATABASE shop`;\nexport const e = table`CREATE TABLE ${shop}.e (k String) ENGINE = MergeTree ORDER BY k`;\n');
    expect(await drizzle()).toBe(1);
    expect(errors.join("\n")).toContain("Drizzle has no clickhouse dialect");
  }, 30_000);

  test("changing a column without regenerating fails the workspace's generated-file check", async () => {
    writeFileSync(
      join(root, "chant.workspace.json"),
      JSON.stringify({
        name: "shop",
        schema: 1,
        members: [{ name: "member", dir: "member", kind: "chant", generated: [{ path: "drizzle-schema.ts", generator: "chant sql drizzle --output drizzle-schema.ts", sources: ["member/src"] }] }],
      }),
    );
    expect(await drizzle()).toBe(0);

    // The generator the check runs is `chant sql drizzle --output <temp>`; it is a process, so the
    // text it would write for the declaration as it now stands is rendered first and handed to a stand-in.
    const standIn = async (): Promise<GeneratorRun> => {
      expect(await drizzle("--output", "next.ts")).toBe(0);
      const text = readFileSync(join(root, "member", "next.ts"), "utf8");
      return ({ argv }) => {
        expect(argv.slice(0, 4)).toEqual(["chant", "sql", "drizzle", "--output"]);
        writeFileSync(argv[4]!, text);
        return { ok: true };
      };
    };
    type GeneratorRun = NonNullable<Parameters<typeof gatherGeneratedFacts>[2]>["runGenerator"];
    const noSkills: RenderSkills = async () => ({ status: "rendered", files: new Map() });
    const findings = async (runGenerator: GeneratorRun) => {
      const facts = await gatherGeneratedFacts(root, readDeclaration(workingTree(root)), { runGenerators: true, renderSkills: noSkills, runGenerator });
      return checkGenerated(facts);
    };

    expect(await findings(await standIn())).toEqual([]);

    write("bigint");
    const stale = await findings(await standIn());
    expect(stale.map((f) => [f.id, f.severity, f.path])).toEqual([[WSP_GENERATED_DRIFT, "error", "member/drizzle-schema.ts"]]);
    expect(stale[0]!.message).toContain("differs from what `chant sql drizzle --output drizzle-schema.ts` writes");

    expect(await drizzle()).toBe(0);
    expect(await findings(await standIn())).toEqual([]);
  }, 60_000);
});
