    expect(r.text).toContain('check("orders_amount_check", sql`amount >= 0`),');
    expect(r.text).toContain('index("orders_user_id_idx").on(t.user_id, t.placed_at.desc().nullsFirst()),');
    expect(r.text).toContain('unique("users_email_key").on(t.email),');
    expect(r.text).toContain('}).existing();');
