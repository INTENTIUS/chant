const entities = (o: Record<string, unknown>) => new Map(Object.entries(o)) as Map<string, Declarable>;

describe("the row type mapping covers the pinned catalogs", () => {
  test("every Postgres built-in type of every supported major has a row type, and nothing else does", () => {
    expect(Object.keys(POSTGRES_ROW_TYPES).sort()).toEqual(Object.keys(COLUMN_TYPES).sort());
  });

  test("every ClickHouse type family has a row type, and nothing else does", () => {
    const families = [...new Set(Object.values(TYPE_FAMILIES).map((f) => f.canonical))].sort();
    expect(Object.keys(CLICKHOUSE_ROW_TYPES).sort()).toEqual(families);
  });

  test("ClickHouse wrappers and containers compose; an alias reads as its family", () => {
    expect(clickhouseRowType("Nullable(UInt64)")).toEqual({ ts: "string", nullable: true });
    expect(clickhouseRowType("LowCardinality(Nullable(String))")).toEqual({ ts: "string", nullable: true });
    expect(clickhouseRowType("Array(Nullable(Int32))").ts).toBe("(number | null)[]");
    expect(clickhouseRowType("Map(String, Array(UInt8))").ts).toBe("Record<string, number[]>");
    expect(clickhouseRowType("Tuple(String, UInt8)").ts).toBe("[string, number]");
    expect(clickhouseRowType("Enum8('a' = 1, 'it''s' = 2)").ts).toBe('"a" | "it\'s"');
    expect(clickhouseRowType("BIGINT UNSIGNED").ts).toBe("string");
    expect(clickhouseRowType("SimpleAggregateFunction(sum, Float64)").ts).toBe("number");
    expect(clickhouseRowType("NoSuchType").ts).toBe("unknown");
  });
});

describe("the slots a tag records", () => {
  test("a Postgres foreign key's interpolated referenced column, paired with the referencing column, off the output", () => {
    const s = pg.schema`CREATE SCHEMA shop`;
    const a = pg.table`CREATE TABLE ${s}.a (id bigint PRIMARY KEY, code text UNIQUE)`;
    const b = pg.table<"shop.b">`
      CREATE TABLE ${s}.b (
        a_id bigint REFERENCES ${a} (${a.columns.id}),
        a_code text,
        FOREIGN KEY (a_code) REFERENCES ${a} (${a.columns.code}),
        other bigint REFERENCES ${a}
      )`;
    expect(getTypedSlots(b)).toEqual([
      { index: 2, kind: "references", column: "a_id" },
      { index: 4, kind: "references", column: "a_code" },
    ]);
    expect(Object.getOwnPropertySymbols(b).some((k) => Object.getOwnPropertyDescriptor(b, k)!.enumerable)).toBe(false);
    const out = sqlSerializer.serialize(entities({ s, a, b })) as { primary: string };
    expect(out.primary).not.toContain("references\", \"column");
  });

  test("a ClickHouse sort key's bare interpolated columns, and nothing inside an expression", () => {
    const db = ch.database`CREATE DATABASE shop`;
    const e = ch.table`CREATE TABLE ${db}.e (k String, c Nullable(String), n UInt8) ENGINE = MergeTree ORDER BY k`;
    const v = ch.view`
      CREATE MATERIALIZED VIEW ${db}.v ENGINE = MergeTree
      ORDER BY (${e.columns.k}, ifNull(${e.columns.c}, ''))
      PRIMARY KEY ${e.columns.k}
      AS SELECT ${e.columns.k}, ${e.columns.c} FROM ${e}`;
    expect(getTypedSlots(v)).toEqual([
      { index: 1, kind: "sortKey" },
      { index: 3, kind: "sortKey" },
    ]);
  });
});

describe("renderSqlTypes", () => {
  test("keys are qualified and folded, a view passes its column through, slots stop at the last checked one", () => {
    const s = pg.schema`CREATE SCHEMA Shop`;
    const users = pg.table`CREATE TABLE ${s}.Users (Id serial PRIMARY KEY, mood text, born date NOT NULL)`;
    const posts = pg.table`CREATE TABLE ${s}.posts (author integer REFERENCES ${users} (${users.columns.id}), body text)`;
    const feed = pg.view`CREATE VIEW ${s}.feed AS SELECT p.${posts.columns.body}, upper(p.${posts.columns.body}) AS loud FROM ${posts} p`;
    const text = renderSqlTypes(entities({ s, users, posts, feed }), { projectDir: "/" });
    expect(text.split("\n")[0]).toContain("Generated by chant");
    expect(text).toContain('import type { Column, KeyColumn } from "@intentius/chant-lexicon-sql/postgres";');
    expect(text).toContain('"shop.users": {');
    expect(text).toContain('id: Column<"integer", { ts: number; nullable: false; cmp: "N" }>;');
    expect(text).toContain('born: Column<"date", { ts: Date; nullable: false; cmp: "D" }>;');
    expect(text).toContain("slots: [unknown, unknown, KeyColumn<\"N\">];");
    expect(text).toContain('body: Column<"text", { ts: string; nullable: true; cmp: "S" }>;');
    expect(text).toContain('loud: Column<"unknown", { ts: unknown; nullable: never; cmp: never }>;');
    expect(text.indexOf('"shop.feed"')).toBeLessThan(text.indexOf('"shop.posts"'));
  });

  test("with nothing declared, a module that augments nothing", () => {
    expect(renderSqlTypes(new Map(), { config: { sql: { dialect: "postgres" } } })).toBe(
      [
        "// Generated by chant — do not edit directly. `chant sql types` writes it from the build's entities.",
        'import type {} from "@intentius/chant-lexicon-sql/postgres";',
        "",
        'declare module "@intentius/chant-lexicon-sql/postgres" {',
        "  interface SqlSchema {}",
        "}",
        "",
      ].join("\n"),
    );
  });

  test("relationKey: qualified when the DDL qualifies it", () => {
    expect(relationKey({ schema: "app", name: "users" })).toBe("app.users");
    expect(relationKey({ database: "shop", name: "events" })).toBe("shop.events");
    expect(relationKey({ name: "events" })).toBe("events");
  });
});

describe("chant sql types", () => {
  test("refuses to write beside a sql-types.ts, which tsc would read instead", async () => {
    const dir = mkdtempSync(join(tmpdir(), "sql-types-"));
    writeFileSync(join(dir, "sql-types.ts"), "export {};\n");
    expect(shadowingSource(join(dir, "sql-types.d.ts"))).toBe(join(dir, "sql-types.ts"));
    expect(shadowingSource(join(dir, "other.d.ts"))).toBeUndefined();
    const cwd = process.cwd();
    process.chdir(dir);
    try {
      expect(await runTypes({ verb: "types", rawArgs: ["--output", "sql-types.d.ts"] })).toBe(1);
      expect(await runTypes({ verb: "types", rawArgs: ["--bogus"] })).toBe(1);
    } finally {
      process.chdir(cwd);
    }
    expect(readFileSync(join(dir, "sql-types.ts"), "utf8")).toBe("export {};\n");
  });
});
