import { describe, expect, test } from "vitest";
import type { Declarable } from "@intentius/chant/declarable";
import { COLUMN_TYPES } from "./generated/postgres";
import { TYPE_FAMILIES } from "./generated/clickhouse";
import { POSTGRES_ROW_TYPES } from "./postgres/row-types";
import { CLICKHOUSE_ROW_TYPES, clickhouseRowType } from "./clickhouse/row-types";
import * as pg from "./postgres/entities";
