import * as ts from "typescript";
import { mkdirSync, mkdtempSync, realpathSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, test } from "vitest";
import type { LintContext } from "@intentius/chant/lint/rule";
import { sqlch004 } from "./sqlch004";
import { sqlpg005 } from "./sqlpg005";
import { nameAgrees, namesInGenerated, normalizedName, splitQualified } from "./typed-names";

const PG = "@intentius/chant-lexicon-sql/postgres";
const CH = "@intentius/chant-lexicon-sql/clickhouse";

const ctx = (code: string, filePath = "schema.ts"): LintContext => ({
  sourceFile: ts.createSourceFile(filePath, code, ts.ScriptTarget.Latest, true),
  entities: [],
  filePath,
});

const generated = (module: string, names: string[]): string =>
  `// Generated by chant — do not edit directly.\nimport type { Column } from "${module}";\n\ndeclare module "${module}" {\n  interface SqlSchema {\n` +
  names.map((n) => `    /** src/schema.ts */\n    ${JSON.stringify(n)}: { columns: { id: Column<"bigint", { ts: string; nullable: false; cmp: "N" }> } };\n`).join("") +
  "  }\n}\n";

/** A project directory with the generated file in src/ and a source file under src/db/. */
function project(module: string, names: string[] | undefined): string {
  const root = realpathSync(mkdtempSync(join(tmpdir(), "chant-3751-")));
  mkdirSync(join(root, "src", "db"), { recursive: true });
  writeFileSync(join(root, "chant.config.json"), "{}");
  if (names) writeFileSync(join(root, "src", "sql-types.d.ts"), generated(module, names));
  return join(root, "src", "db", "schema.ts");
}

describe("typed-names helpers", () => {
  test("splitQualified takes quotes off and splits outside them", () => {
    expect(splitQualified('shop."Order.Items"')).toEqual(["shop", "Order.Items"]);
    expect(splitQualified("orders")).toEqual(["orders"]);
    expect(normalizedName('"shop"."orders"')).toBe(normalizedName("shop.orders"));
  });

  test("nameAgrees compares from the last piece and skips interpolations", () => {
    expect(nameAgrees(["shop", "orders"], "shop.orders")).toBe(true);
    expect(nameAgrees(["orders"], "shop.orders")).toBe(true);
    expect(nameAgrees(["", "orders"], "shop.orders")).toBe(true);
    expect(nameAgrees(["shop", "orders"], "orders")).toBe(false);
    expect(nameAgrees(["shop", "orders"], "shop.ordrs")).toBe(false);
    expect(nameAgrees(["other", "orders"], "shop.orders")).toBe(false);
  });

  test("namesInGenerated reads only the module's SqlSchema", () => {
    const text = generated(PG, ["shop.orders", "shop.users"]);
    expect(namesInGenerated(text, PG)).toEqual(new Set([normalizedName("shop.orders"), normalizedName("shop.users")]));
    expect(namesInGenerated(text, CH)).toBeUndefined();
  });
});

const PGX = `import { table, view } from "${PG}";\n`;
const CHX = `import { table, view, dictionary } from "${CH}";\n`;

describe("SQLPG005: a typed Postgres tag's type argument", () => {
  test("a name that agrees with the template, with no generated file, is clean", () => {
    const code = `${PGX}export const o = table<"shop.orders">\`CREATE TABLE shop.orders (id bigint)\`;`;
    expect(sqlpg005.check(ctx(code))).toEqual([]);
  });

  test("a different name is an error, at the type argument", () => {
    const code = `${PGX}export const o = table<"shop.ordrs">\`CREATE TABLE shop.orders (id bigint)\`;`;
    const [d, ...rest] = sqlpg005.check(ctx(code));
    expect(rest).toEqual([]);
    expect(d).toMatchObject({ ruleId: "SQLPG005", severity: "error", line: 2, column: 24 });
    expect(d!.message).toContain("shop.orders");
  });

  test("a schema that is an interpolation is left out of the comparison", () => {
    const ok = `${PGX}import { shopSchema } from "./s";\nexport const o = table<"shop.orders">\`CREATE TABLE \${shopSchema}.orders (id bigint)\`;`;
    expect(sqlpg005.check(ctx(ok))).toEqual([]);
    const bad = ok.replace("shop.orders", "shop.items");
    expect(sqlpg005.check(ctx(bad))).toHaveLength(1);
  });

  test("a view is read too, and quoting and case folding follow Postgres", () => {
    const ok = `${PGX}export const v = view<"app.order_totals">\`CREATE VIEW App."order_totals" AS SELECT 1\`;`;
    expect(sqlpg005.check(ctx(ok))).toEqual([]);
    const bad = `${PGX}export const v = view<"app.Order_Totals">\`CREATE VIEW app.order_totals AS SELECT 1\`;`;
    expect(sqlpg005.check(ctx(bad))).toHaveLength(1);
  });

  test("a tag with no type argument, or a non-literal one, is not read", () => {
    expect(sqlpg005.check(ctx(`${PGX}export const o = table\`CREATE TABLE shop.orders (id bigint)\`;`))).toEqual([]);
    expect(sqlpg005.check(ctx(`${PGX}export const o = table<string>\`CREATE TABLE shop.orders (id bigint)\`;`))).toEqual([]);
  });

  test("a tag from another module, or the ClickHouse tag, is not read", () => {
    expect(sqlpg005.check(ctx(`import { table } from "./mine";\nexport const o = table<"x.y">\`not sql\`;`))).toEqual([]);
    expect(sqlpg005.check(ctx(`${CHX}export const o = table<"a.b">\`CREATE TABLE c.d (id UInt64) ENGINE = Log\`;`))).toEqual([]);
  });

  test("a template that does not parse is SQLPG001's to report", () => {
    expect(sqlpg005.check(ctx(`${PGX}export const o = table<"a.b">\`CREATE TABLE\`;`))).toEqual([]);
  });

  test("a name the generated file lacks is a warning; one it lists is clean", () => {
    const file = project(PG, ["shop.users"]);
    const code = `${PGX}export const o = table<"shop.orders">\`CREATE TABLE shop.orders (id bigint)\`;\nexport const u = table<"shop.users">\`CREATE TABLE shop.users (id bigint)\`;`;
    const diags = sqlpg005.check(ctx(code, file));
    expect(diags).toHaveLength(1);
    expect(diags[0]).toMatchObject({ ruleId: "SQLPG005", severity: "warning", line: 2 });
    expect(diags[0]!.message).toMatch(/not in sql-types\.d\.ts.*chant sql types/);
  });

  test("a generated file with no block for the dialect is silent", () => {
    const file = project(CH, ["shop.events"]);
    const code = `${PGX}export const o = table<"shop.orders">\`CREATE TABLE shop.orders (id bigint)\`;`;
    expect(sqlpg005.check(ctx(code, file))).toEqual([]);
  });
});

describe("SQLCH004: a typed ClickHouse tag's type argument", () => {
  const ddl = (db: string) => `CREATE TABLE ${db}.events (id UInt64) ENGINE = Log`;

  test("a name that agrees is clean; a different one is an error", () => {
    expect(sqlch004.check(ctx(`${CHX}export const e = table<"shop.events">\`${ddl("shop")}\`;`))).toEqual([]);
    const [d] = sqlch004.check(ctx(`${CHX}export const e = table<"shop.event">\`${ddl("shop")}\`;`));
    expect(d).toMatchObject({ ruleId: "SQLCH004", severity: "error", line: 2 });
  });

  test("a database that is an interpolation is left out, and a name differing in case is a different name", () => {
    expect(sqlch004.check(ctx(`${CHX}import { db } from "./d";\nexport const e = table<"shop.events">\`${ddl("${db}")}\`;`))).toEqual([]);
    expect(sqlch004.check(ctx(`${CHX}export const e = table<"shop.Events">\`${ddl("shop")}\`;`))).toHaveLength(1);
  });

  test("a dictionary and a view are read", () => {
    const dict = `${CHX}export const d = dictionary<"shop.codes">\`CREATE DICTIONARY shop.codes (id UInt64) PRIMARY KEY id SOURCE(CLICKHOUSE(TABLE 'c')) LAYOUT(FLAT()) LIFETIME(0)\`;`;
    expect(sqlch004.check(ctx(dict))).toEqual([]);
    expect(sqlch004.check(ctx(dict.replace("shop.codes\"", "shop.cods\"")))).toHaveLength(1);
    const view = `${CHX}export const v = view<"shop.v1">\`CREATE VIEW shop.v2 AS SELECT 1\`;`;
    expect(sqlch004.check(ctx(view))).toHaveLength(1);
  });

  test("a name the generated file lacks is a warning", () => {
    const file = project(CH, ["shop.other"]);
    const [d] = sqlch004.check(ctx(`${CHX}export const e = table<"shop.events">\`${ddl("shop")}\`;`, file));
    expect(d).toMatchObject({ ruleId: "SQLCH004", severity: "warning" });
    expect(sqlch004.check(ctx(`${CHX}export const e = table<"shop.other">\`CREATE TABLE shop.other (id UInt64) ENGINE = Log\`;`, file))).toEqual([]);
  });

  test("without a generated file only the name comparison runs", () => {
    const file = project(CH, undefined);
    expect(sqlch004.check(ctx(`${CHX}export const e = table<"shop.events">\`${ddl("shop")}\`;`, file))).toEqual([]);
  });
});
