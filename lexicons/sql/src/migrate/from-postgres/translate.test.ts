import { describe, expect, test } from "vitest";
import { sqlFileEntities } from "../../sql-files";
import { table as clickhouseTable } from "../../clickhouse/entities";
import { emitSql, emitTs, mirrorObjects, tableSql } from "./emit";
import { looksLikePostgres } from "./detect";
import { transform } from "./index";
import { translatePostgres, type Translation } from "./translate";

const entities = (ddl: string) => sqlFileEntities("postgres", [{ ddl, origin: "schema.sql" }], { known: new Map() });
const run = (ddl: string, composite = false): Translation => translatePostgres(entities(ddl), { composite });
const rules = (t: Translation, entity?: string) => t.diagnostics.filter((d) => entity === undefined || d.entity === entity).map((d) => d.ruleId);
const find = (t: Translation, ruleId: string, text = "") => t.diagnostics.find((d) => d.ruleId === ruleId && d.message.includes(text));

describe("sort key and engine", () => {
  test("the primary key is the sort key; a composite key keeps its order", () => {
    const t = run("CREATE TABLE docs (tenant_id bigint NOT NULL, id bigint NOT NULL, body text NOT NULL, PRIMARY KEY (tenant_id, id))");
    expect(t.mirrors[0]!.primaryKey).toEqual(["tenant_id", "id"]);
    expect(find(t, "SQLRV001")!.message).toContain("ORDER BY (tenant_id, id) suggested from the primary key");
    expect(tableSql(t.mirrors[0]!)).toContain("ORDER BY (tenant_id, id)");
  });

  test("with no primary key the first unique key is the sort key, and the finding says it passed over nothing else", () => {
    const t = run("CREATE TABLE docs (slug text NOT NULL UNIQUE, body text NOT NULL)");
    expect(t.mirrors[0]!.primaryKey).toEqual(["slug"]);
    expect(find(t, "SQLRV001")!.message).toContain("unique key");
  });

  test("with no key at all the sort key is tuple(), and the engine finding still warns", () => {
    const t = run("CREATE TABLE log (line text NOT NULL)");
    expect(t.mirrors[0]!.primaryKey).toEqual([]);
    expect(find(t, "SQLRV001")!.message).toContain("tuple()");
    expect(tableSql(t.mirrors[0]!)).toContain("ORDER BY tuple()");
    expect(find(t, "SQLRV002")!.severity).toBe("warning");
  });

  test("every table gets the ReplacingMergeTree engine with the two columns the composite names", () => {
    const sql = tableSql(run("CREATE TABLE t (id bigint PRIMARY KEY)").mirrors[0]!);
    expect(sql).toContain("ENGINE = ReplacingMergeTree(_version, _is_deleted)");
    expect(sql).toContain("_version UInt64");
    expect(sql).toContain("_is_deleted UInt8");
  });

  test("a source column named like one the mirror adds refuses the table with an error", () => {
    const t = run("CREATE TABLE t (id bigint PRIMARY KEY, _version int)");
    expect(t.mirrors).toEqual([]);
    expect(find(t, "SQLRV011", "_version")).toMatchObject({ severity: "error" });
  });

  test("a nullable unique key needs allow_nullable_key, which a CdcMirror call cannot carry", () => {
    const ddl = "CREATE TABLE t (code text UNIQUE, n int NOT NULL)";
    const bare = run(ddl);
    expect(tableSql(bare.mirrors[0]!)).toContain("SETTINGS allow_nullable_key = 1");
    const composite = run(ddl, true);
    expect(find(composite, "SQLRV001", "no SETTINGS")).toMatchObject({ severity: "warning" });
  });
});

describe("Nullable, defaults and column kinds", () => {
  test("a nullable column is Nullable with a finding, and a default is named as the way out", () => {
    const t = run("CREATE TABLE t (id bigint PRIMARY KEY, note text, qty integer DEFAULT 0, tag text NOT NULL)");
    const types = Object.fromEntries(t.mirrors[0]!.columns.map((c) => [c.name, c.type]));
    expect(types).toEqual({ id: "Int64", note: "Nullable(String)", qty: "Nullable(Int32)", tag: "String" });
    expect(find(t, "SQLRV003", "t.qty")!.message).toContain("DEFAULT 0");
    expect(find(t, "SQLRV003", "t.note")!.message).toContain("no default");
    expect(t.diagnostics.filter((d) => d.ruleId === "SQLRV003")).toHaveLength(2);
  });

  test("a primary key, identity and serial column are not Nullable whatever the DDL says", () => {
    const t = run("CREATE TABLE t (a bigint PRIMARY KEY, b bigint GENERATED BY DEFAULT AS IDENTITY, c serial, d bigint NOT NULL)");
    expect(t.mirrors[0]!.columns.map((c) => c.type)).toEqual(["Int64", "Int64", "Int32", "Int64"]);
    expect(rules(t).filter((r) => r === "SQLRV003")).toEqual([]);
    expect(t.diagnostics.filter((d) => d.ruleId === "SQLRV006").map((d) => d.severity)).toEqual(["info", "info"]);
  });

  test("an array is not Nullable and says why", () => {
    const t = run("CREATE TABLE t (id bigint PRIMARY KEY, tags text[])");
    expect(t.mirrors[0]!.columns[1]!.type).toBe("Array(String)");
    expect(find(t, "SQLRV007", "t.tags")!.message).toContain("Array(String)");
    expect(rules(t)).not.toContain("SQLRV003");
  });

  test("a stored generated column is a warning; the type judgments are warnings; a default is an info", () => {
    const t = run("CREATE TABLE t (id bigint PRIMARY KEY, a int NOT NULL, b int GENERATED ALWAYS AS (a * 2) STORED, m money NOT NULL, ts timestamptz NOT NULL DEFAULT now())");
    expect(find(t, "SQLRV006", "t.b")).toMatchObject({ severity: "warning" });
    expect(find(t, "SQLRV007", "money")).toMatchObject({ severity: "warning" });
    expect(find(t, "SQLRV008", "t.ts")).toMatchObject({ severity: "info" });
    expect(t.mirrors[0]!.columns.find((c) => c.name === "ts")!.type).toBe("DateTime64(6, 'UTC')");
    expect(tableSql(t.mirrors[0]!)).not.toContain("DEFAULT");
  });

  test("the type of an enum or extension column is a judgment, never silent", () => {
    const t = run("CREATE TABLE t (id bigint PRIMARY KEY, mood citext NOT NULL, geo geometry NOT NULL)");
    expect(find(t, "SQLRV007", "t.geo")).toBeDefined();
    expect(find(t, "SQLRV007", "t.mood")).toBeUndefined();
  });

  test("a column comment is kept as COMMENT; a table comment is kept bare and noted under a composite", () => {
    const ddl = "CREATE TABLE t (id bigint PRIMARY KEY, email text NOT NULL); COMMENT ON COLUMN t.email IS 'PII'; COMMENT ON TABLE t IS 'The accounts'";
    const bare = run(ddl);
    expect(tableSql(bare.mirrors[0]!)).toContain("email String COMMENT 'PII'");
    expect(tableSql(bare.mirrors[0]!)).toContain("COMMENT 'The accounts'");
    const composite = run(ddl, true);
    expect(find(composite, "SQLRV011", "description")).toMatchObject({ severity: "info" });
    expect(emitTs(composite.mirrors, true)).toContain("email String COMMENT 'PII'");
  });
});

describe("constraints, indexes and storage", () => {
  const ddl = `
    CREATE TABLE a (id bigint PRIMARY KEY);
    CREATE TABLE b (
      id bigint PRIMARY KEY,
      a_id bigint NOT NULL REFERENCES a (id),
      code text NOT NULL UNIQUE,
      qty int NOT NULL CHECK (qty > 0),
      during tstzrange,
      EXCLUDE USING gist (during WITH &&)
    ) WITH (fillfactor = 70);
    CREATE UNIQUE INDEX b_code_lower ON b (lower(code));
    CREATE INDEX b_qty ON b (qty);`;

  test("foreign keys, uniques, checks and exclusions are findings and comment lines", () => {
    const t = run(ddl);
    const b = t.mirrors.find((m) => m.name === "b")!;
    expect(b.constraintComments).toEqual([
      "-- FOREIGN KEY (a_id) REFERENCES a (id)",
      "-- UNIQUE (code)",
      "-- CHECK qty > 0",
      "-- EXCLUDE USING gist (during WITH &&)",
    ]);
    expect(t.diagnostics.filter((d) => d.ruleId === "SQLRV005" && d.entity === "b")).toHaveLength(4);
    expect(tableSql(b).split("\n").slice(0, 4)).toEqual(b.constraintComments);
  });

  test("an index that is not a plain unique key, and the storage options, are warnings", () => {
    const t = run(ddl);
    expect(find(t, "SQLRV009", "b_qty")).toMatchObject({ severity: "warning", entity: "b" });
    expect(find(t, "SQLRV009", "b_code_lower")).toBeDefined();
    expect(find(t, "SQLRV009", "Storage options")!.message).toContain("WITH (fillfactor = 70)");
  });

  test("a view, a sequence and a partition are named as not carried", () => {
    const t = run(`
      CREATE TABLE events (id bigint, at timestamptz NOT NULL) PARTITION BY RANGE (at);
      CREATE TABLE events_2026 PARTITION OF events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01');
      CREATE VIEW recent AS SELECT * FROM events;
      CREATE SEQUENCE ticket_seq;`);
    expect(t.mirrors.map((m) => m.name)).toEqual(["events"]);
    expect(t.diagnostics.filter((d) => d.ruleId === "SQLRV011").map((d) => d.entity).sort()).toEqual(["events_2026", "sequence ticket_seq", "view recent"]);
    expect(find(t, "SQLRV009", "PARTITION BY RANGE")).toBeDefined();
  });

  test("two schemas with one table name keep the schema as a database qualifier", () => {
    const t = run("CREATE SCHEMA a; CREATE SCHEMA b; CREATE TABLE a.items (id bigint PRIMARY KEY); CREATE TABLE b.items (id bigint PRIMARY KEY); CREATE TABLE b.other (id bigint PRIMARY KEY)");
    expect(t.mirrors.map((m) => m.name)).toEqual(["a.items", "b.items", "other"]);
    expect(t.outputs).toContain("b.items.id");
    expect(find(t, "SQLRV011", "keeps its schema")).toBeDefined();
  });
});

describe("what is written", () => {
  const t = run("CREATE TABLE accounts (tenant_id bigint NOT NULL, id bigint NOT NULL, name text NOT NULL, PRIMARY KEY (tenant_id, id)); CREATE TABLE \"Odd Name\" (id bigint PRIMARY KEY)");
  const plain = run("CREATE TABLE accounts (tenant_id bigint NOT NULL, id bigint NOT NULL, name text NOT NULL, PRIMARY KEY (tenant_id, id))", true);

  test("--emit ts with composites is CdcMirror calls with the sort key as primaryKey", () => {
    const ts = emitTs(plain.mirrors, true);
    expect(ts).toContain('import { CdcMirror } from "@intentius/chant-lexicon-sql/clickhouse";');
    expect(ts).toContain('primaryKey: "(tenant_id, id)"');
    expect(ts).toContain('columns: "tenant_id Int64, id Int64, name String"');
  });

  test("--emit ts without composites is table declarations whose DDL the ClickHouse tag reads", () => {
    const ts = emitTs(t.mirrors, false);
    expect(ts).toContain('import { table } from "@intentius/chant-lexicon-sql/clickhouse";');
    for (const m of t.mirrors) {
      const sql = tableSql(m);
      const entity = clickhouseTable(Object.assign([sql], { raw: [sql] }) as unknown as TemplateStringsArray);
      const props = (entity as unknown as { props: { engine: { name: string; args: string[] }; columns: Array<{ name: string }> } }).props;
      expect(props.engine).toMatchObject({ name: "ReplacingMergeTree", args: ["_version", "_is_deleted"] });
      expect(props.columns.map((c) => c.name).slice(-2)).toEqual(["_version", "_is_deleted"]);
    }
  });

  test("--emit sql ends each statement; a composite adds the view of live rows", () => {
    const sql = emitSql(plain.mirrors, true);
    expect(sql.match(/^CREATE (TABLE|VIEW)/gm)).toHaveLength(2);
    expect(sql).toContain("CREATE VIEW accounts_current AS");
    expect(sql.trimEnd().endsWith(";")).toBe(true);
    expect(mirrorObjects(t.mirrors, false).map((o) => o.name)).toEqual(["accounts", "Odd Name"]);
  });

  test("a name that needs quoting is quoted in DDL, and refused for a CdcMirror call, which writes it bare", () => {
    expect(tableSql(t.mirrors[1]!)).toContain("CREATE TABLE `Odd Name`");
    const composite = run('CREATE TABLE "Odd Name" (id bigint PRIMARY KEY)', true);
    expect(composite.mirrors).toEqual([]);
    expect(find(composite, "SQLRV011", "needs quoting")).toMatchObject({ severity: "error" });
  });
});

describe("transform: the MigrationSource's result", () => {
  const ddl = "CREATE TABLE t (id bigint PRIMARY KEY, status text NOT NULL, note text);";

  test("findings are SARIF-shaped diagnostics against the source file; links name the Postgres outputs", async () => {
    const r = await transform(ddl, { emit: "ts", useComposites: true, sourceFile: "db/schema.sql" });
    expect(r.diagnostics.every((d) => d.file === "db/schema.sql" && d.line === 1 && d.column === 1)).toBe(true);
    expect(new Set(r.diagnostics.map((d) => d.ruleId))).toEqual(new Set(["SQLRV001", "SQLRV002", "SQLRV003", "SQLRV004"]));
    expect(r.links).toEqual(["public.t.id", "public.t.status", "public.t.note"]);
    expect(r.output).toContain("CdcMirror({");
    expect(r.provenance).toHaveLength(1);
    expect(typeof r.validate).toBe("function");
  });

  test("--strict makes every open warning an error and leaves info alone", async () => {
    const lax = await transform(ddl, { emit: "ts" });
    const strict = await transform(ddl, { emit: "ts", strict: true });
    expect(lax.diagnostics.some((d) => d.severity === "error")).toBe(false);
    const warnings = lax.diagnostics.filter((d) => d.severity === "warning").length;
    expect(warnings).toBeGreaterThan(0);
    expect(strict.diagnostics.filter((d) => d.severity === "error")).toHaveLength(warnings);
    expect(strict.diagnostics.filter((d) => d.severity === "warning")).toEqual([]);
  });

  test("a table with nothing left to decide still has the sort key and engine open, so strict has something to fail on", async () => {
    const r = await transform("CREATE TABLE t (id bigint PRIMARY KEY);", { emit: "sql", strict: true });
    expect(r.diagnostics.filter((d) => d.severity === "error").map((d) => d.ruleId)).toEqual(["SQLRV001", "SQLRV002"]);
  });

  test("--emit yaml is refused, and a file with no table to mirror fails by name", async () => {
    await expect(transform(ddl, { emit: "yaml" })).rejects.toThrow("--emit yaml");
    await expect(transform("CREATE VIEW v AS SELECT 1;", { emit: "ts", sourceFile: "x.sql" })).rejects.toThrow("no Postgres table to mirror in x.sql");
  });
});

describe("looksLikePostgres", () => {
  test("recognises Postgres DDL and declarations, and not ClickHouse or T-SQL", () => {
    expect(looksLikePostgres("CREATE TABLE t (id int);")).toBe(true);
    expect(looksLikePostgres('import { table } from "@intentius/chant-lexicon-sql/postgres";')).toBe(true);
    expect(looksLikePostgres("CREATE TABLE t (id UInt64) ENGINE = MergeTree ORDER BY id")).toBe(false);
    expect(looksLikePostgres("CREATE TABLE t (id int)\nGO\n")).toBe(false);
    expect(looksLikePostgres("SELECT 1")).toBe(false);
  });
});
