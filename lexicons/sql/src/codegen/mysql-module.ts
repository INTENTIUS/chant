/**
 * Render the MySQL dialect's generated surface from its catalog (#5449):
 *
 * - `src/generated/mysql-types.ts`: string-literal unions of every column type
 *   (canonical names, and every spelling the server accepts), storage engine,
 *   character set, index type, row format, referential action and column
 *   attribute, and the reserved words.
 * - `src/generated/mysql.ts`: the tables lint and the LSP read: each type's
 *   family, aliases, parameters and attributes, each engine and character set.
 *
 * Output depends only on the catalog: every list is walked in the catalog's
 * (sorted) order, so two runs are byte-identical.
 */

import { mysqlCatalogProblems, type MysqlCatalog } from "../spec/mysql-catalog";

export interface RenderedMysqlModule {
  /** `src/generated/mysql-types.ts`. */
  declarations: string;
  /** `src/generated/mysql.ts`. */
  tables: string;
}

const lit = (names: readonly string[]): string => (names.length > 0 ? names.map((n) => JSON.stringify(n)).join(" | ") : "never");
const key = (name: string): string => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name));

export function renderMysqlModule(catalog: MysqlCatalog): RenderedMysqlModule {
  const problems = mysqlCatalogProblems(catalog);
  if (problems.length > 0) throw new Error(`the MySQL ${catalog.major} catalog is not whole:\n  ${problems.join("\n  ")}`);
  const header = `// Generated by \`npm run generate\` from the MySQL ${catalog.major} catalog (${catalog.version}, ${catalog.source})\n// (src/spec/mysql-catalog-${catalog.major}.snapshot.json). Do not edit.\n`;

  const typeNames = catalog.types.map((t) => t.name);
  const spellings = catalog.types.flatMap((t) => [t.name, ...t.aliases]).sort();
  const declarations = [
    header,
    `/** The MySQL major line the types are for. */`,
    `export const MYSQL_MAJOR = ${JSON.stringify(catalog.major)};`,
    `/** The minor the catalog was checked against. */`,
    `export const MYSQL_VERSION = ${JSON.stringify(catalog.version)};`,
    ``,
    `/** A column type, by its canonical name. */`,
    `export type MysqlTypeName = ${lit(typeNames)};`,
    `/** A column type, in any spelling the server accepts. */`,
    `export type MysqlTypeSpelling = ${lit(spellings)};`,
    `/** A storage engine. */`,
    `export type MysqlEngine = ${lit(catalog.engines.map((e) => e.name))};`,
    `/** A character set. */`,
    `export type MysqlCharset = ${lit(catalog.charsets.map((c) => c.name))};`,
    `/** An index kind: \`BTREE\` and \`HASH\` for \`USING\`, \`FULLTEXT\` and \`SPATIAL\` as the index's own kind. */`,
    `export type MysqlIndexType = ${lit(catalog.indexTypes)};`,
    `/** A \`ROW_FORMAT\`. */`,
    `export type MysqlRowFormat = ${lit(catalog.rowFormats)};`,
    `/** A foreign key's \`ON DELETE\` or \`ON UPDATE\` action. */`,
    `export type MysqlReferentialAction = ${lit(catalog.referentialActions)};`,
    `/** A clause of a column definition beside its type. */`,
    `export type MysqlColumnAttribute = ${lit(catalog.columnAttributes)};`,
    `/** A word that needs quoting as an identifier. */`,
    `export type MysqlReservedWord = ${lit(catalog.keywords.filter((k) => k.reserved).map((k) => k.word))};`,
    ``,
  ].join("\n");

  const tables = [
    header,
    `import type { CharsetRow, EngineRow, TypeRow } from "../spec/mysql-catalog";`,
    `import type { MysqlCharset, MysqlEngine, MysqlReservedWord, MysqlTypeName, MysqlTypeSpelling } from "./mysql-types";`,
    ``,
    `export * from "./mysql-types";`,
    ``,
    `/** Each column type: its family, the other spellings, what its parentheses take, and its attributes. */`,
    `export const COLUMN_TYPES: Readonly<Record<MysqlTypeName, Omit<TypeRow, "name">>> = {`,
    ...catalog.types.map((t) => `  ${key(t.name)}: ${JSON.stringify({ family: t.family, aliases: t.aliases, parameters: t.parameters, attributes: t.attributes })},`),
    `};`,
    ``,
    `/** Every spelling of a column type, and the canonical name it is. */`,
    `export const TYPE_SPELLINGS: Readonly<Record<MysqlTypeSpelling, MysqlTypeName>> = {`,
    ...catalog.types.flatMap((t) => [t.name, ...t.aliases].map((s) => [s, t.name] as const)).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0)).map(([s, n]) => `  ${key(s)}: ${JSON.stringify(n)},`),
    `};`,
    ``,
    `/** Each storage engine. */`,
    `export const ENGINES: Readonly<Record<MysqlEngine, Omit<EngineRow, "name">>> = {`,
    ...catalog.engines.map((e) => `  ${key(e.name)}: ${JSON.stringify({ declarable: e.declarable, ...(e.default ? { default: true } : {}), transactional: e.transactional })},`),
    `};`,
    ``,
    `/** Each character set, with the collation a column of it gets by default. */`,
    `export const CHARSETS: Readonly<Record<MysqlCharset, Omit<CharsetRow, "name">>> = {`,
    ...catalog.charsets.map((c) => `  ${key(c.name)}: ${JSON.stringify({ defaultCollation: c.defaultCollation, maxLength: c.maxLength })},`),
    `};`,
    ``,
    `/** The words that must be quoted to name an object. */`,
    `export const RESERVED_WORDS: ReadonlySet<MysqlReservedWord> = new Set<MysqlReservedWord>([`,
    ...catalog.keywords.filter((k) => k.reserved).map((k) => `  ${JSON.stringify(k.word)},`),
    `]);`,
    ``,
  ].join("\n");

  return { declarations, tables };
}
