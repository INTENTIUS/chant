/**
 * Generation for the systemone lexicon: there is nothing to generate.
 *
 * The lexicon is verbs only. A decision point is declared in the workspace's
 * points file and validated by core (`decision-points.schema.json`), and the
 * wire format has no resources to type. The registry is still written, empty,
 * because `validate` reads it and `writeBundleSpec` derives `dist/meta.json`
 * from it.
 */

import { writeGeneratedArtifacts } from "@intentius/chant/codegen/generate";
import type { GenerateResult } from "@intentius/chant/codegen/generate";
import { dirname } from "path";
import { fileURLToPath } from "url";

/** Filename of the generated registry, read back by `../validate.ts`. */
export const LEXICON_JSON_FILENAME = "lexicon-systemone.json";

const EMPTY_INDEX_TS = `// Code generated by chant generate. DO NOT EDIT.
// The systemone lexicon models no upstream schema, so there are no resource
// classes to export. See src/codegen/generate.ts.
export {};
`;

const EMPTY_TYPES_DTS = `// Code generated by chant generate. DO NOT EDIT.
export {};
`;

export async function generate(options?: { verbose?: boolean; force?: boolean }): Promise<GenerateResult> {
  if (options?.verbose) console.error("systemone generates no types: it declares no resources");
  return {
    lexiconJSON: `${JSON.stringify({}, null, 2)}\n`,
    typesDTS: EMPTY_TYPES_DTS,
    indexTS: EMPTY_INDEX_TS,
    resources: 0,
    properties: 0,
    enums: 0,
    warnings: [],
  };
}

/** Write generated files to the package directory. */
export function writeGeneratedFiles(result: GenerateResult, pkgDir?: string): void {
  const dir = pkgDir ?? dirname(dirname(dirname(fileURLToPath(import.meta.url))));
  writeGeneratedArtifacts({
    baseDir: dir,
    files: {
      [LEXICON_JSON_FILENAME]: result.lexiconJSON,
      "index.d.ts": result.typesDTS,
      "index.ts": result.indexTS,
    },
  });
}
