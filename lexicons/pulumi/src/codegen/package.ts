/**
 * Packaging for the pulumi lexicon (#4468): `dist/manifest.json` and the
 * rest of the bundle core's `packagePipeline` writes.
 *
 * The lexicon declares no resource types, so there is nothing to generate:
 * the registry is `{}` and the types barrel is empty, the honest statement
 * that it exports no generated classes (the terraform lexicon packages the
 * same way). What the bundle does carry is the manifest, with the
 * `chantVersion` a consumer checks, and the lint and post-synth rule sources
 * under `dist/rules/`, which the docs pipeline reads for the rules page, and
 * the `chant-pulumi` skill (#4494).
 */
import { readFileSync } from "fs";
import { dirname, join } from "path";
import { moduleSourceDir } from "@intentius/chant/module-source";
import { packagePipeline, collectSkills } from "@intentius/chant/codegen/package";
import { pulumiPlugin } from "../plugin";
import type { GenerateResult } from "@intentius/chant/codegen/generate";

/** This package's `src/`, which `packagePipeline` scans for `lint/rules` and `lint/post-synth`. */
const srcDir = dirname(moduleSourceDir(import.meta.url));

/** The published version, so the manifest cannot drift from package.json. */
function packageVersion(): string {
  try {
    const pkg = JSON.parse(readFileSync(join(srcDir, "..", "package.json"), "utf-8")) as { version?: string };
    return pkg.version ?? "0.0.0";
  } catch {
    return "0.0.0";
  }
}

/** The empty generate result: no upstream schema, no generated classes. */
export function emptyGenerateResult(): GenerateResult {
  return {
    lexiconJSON: `${JSON.stringify({}, null, 2)}\n`,
    typesDTS: "// Code generated by chant package. DO NOT EDIT.\n// The pulumi lexicon declares no resource types.\nexport {};\n",
    indexTS: "// Code generated by chant package. DO NOT EDIT.\nexport {};\n",
    resources: 0,
    properties: 0,
    enums: 0,
    warnings: [],
  };
}

export async function packageLexicon(options?: { verbose?: boolean; force?: boolean }) {
  const version = packageVersion();
  return packagePipeline(
    {
      generate: async () => emptyGenerateResult(),
      buildManifest: () => ({
        name: "pulumi",
        version,
        chantVersion: ">=0.1.0",
        namespace: "Pulumi",
      }),
      srcDir,
      collectSkills: () => collectSkills(pulumiPlugin.skills?.() ?? []),
      version,
    },
    options,
  );
}
