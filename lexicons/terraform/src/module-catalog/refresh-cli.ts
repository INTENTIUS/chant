/**
 * Refresh the vendored known-module catalog (chant#4560) from choudoufu's
 * module compatibility table.
 *
 *   npm run --prefix lexicons/terraform module-catalog:refresh -- <choudoufu checkout> [ref]
 *
 * It reads `live/module-compat.json` at `ref` (default `origin/main`) with
 * `git show`, so the checkout's working tree is never read and a local edit
 * cannot leak into the snapshot. The header of the written file names the
 * source path and the choudoufu commit that last changed the table at that
 * ref, so a reader can check the snapshot against its source with
 * `git -C <choudoufu> show <commit>:live/module-compat.json`.
 *
 * Only the static tier is vendored. choudoufu keeps the gauntlet tier in a
 * separate array and the two tiers share no figure (choudoufu#2292 ruling);
 * the gauntlet array stays out until it has rows (choudoufu#2291), and then
 * comes in as its own export, never folded into the static rows.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseModuleCompat, type StaticMeasurement, type StaticRow } from "./types";

const SOURCE_PATH = "live/module-compat.json";
const OUT = join(dirname(fileURLToPath(import.meta.url)), "static-tier.ts");

function git(dir: string, ...args: string[]): string {
  return execFileSync("git", ["-C", dir, ...args], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
}

/** The TypeScript source of `static-tier.ts` for one snapshot. */
export function renderStaticTier(commit: string, measurement: StaticMeasurement, rows: readonly StaticRow[]): string {
  return [
    "// Code generated by src/module-catalog/refresh-cli.ts. DO NOT EDIT.",
    "//",
    `// Vendored from INTENTIUS/choudoufu ${SOURCE_PATH} at commit`,
    `// ${commit}, static tier only (chant#4560).`,
    "// The gauntlet tier is a separate array in that file and is not vendored here.",
    "import type { StaticMeasurement, StaticRow } from \"./types\";",
    "",
    `export const SOURCE_PATH = ${JSON.stringify(SOURCE_PATH)};`,
    `export const SOURCE_COMMIT = ${JSON.stringify(commit)};`,
    "",
    `export const STATIC_MEASUREMENT: StaticMeasurement = ${JSON.stringify(measurement, null, 2)};`,
    "",
    `export const STATIC_ROWS: readonly StaticRow[] = ${JSON.stringify(rows, null, 2)};`,
    "",
  ].join("\n");
}

function main(argv: string[]): void {
  const [dir, ref = "origin/main"] = argv;
  if (!dir) {
    console.error("usage: refresh-cli.ts <choudoufu checkout> [ref]");
    process.exit(2);
  }
  const commit = git(dir, "log", "-1", "--format=%H", ref, "--", SOURCE_PATH).trim();
  if (!/^[0-9a-f]{40}$/.test(commit)) {
    console.error(`${SOURCE_PATH} has no history at ${ref} in ${dir}`);
    process.exit(1);
  }
  const file = parseModuleCompat(JSON.parse(git(dir, "show", `${commit}:${SOURCE_PATH}`)));
  writeFileSync(OUT, renderStaticTier(commit, file.static_measurement, file.static));
  console.log(`module catalog: ${file.static.length} static rows from ${SOURCE_PATH} at ${commit}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
