/**
 * The otel lexicon's generation step (#3361).
 *
 * The built-in components' config types are generated from upstream
 * `config.schema.yaml`, the documents `schemagen` writes next to each
 * component's `config.go`, at the collector-contrib release `COLLECTOR_PIN`
 * names and scoped by the `otelcol-contrib` distribution manifest. Generation
 * reads the committed snapshot (`src/spec/otel-schemas.snapshot.json`, refreshed
 * by `just snapshot`), refuses one that does not match `OTEL_SPEC_PIN`, and
 * writes, into the gitignored `src/generated/`:
 *
 * - `index.ts`: a type alias per schema definition the built-ins reach, and
 *   `<ClassName>SchemaConfig` for each built-in that has a schema. The
 *   hand-written `defineBuiltin` files build their config types on these,
 *   overlaying only what a schema lacks (see `src/components/overlay.ts`);
 * - `properties.json`: each built-in's property tree with upstream's
 *   descriptions, for LSP completion and hover;
 * - `lexicon-otel.json`: the registry, derived from the exported classes.
 *
 * A built-in with no upstream schema (`forward`, which has no config) keeps its
 * hand-written type.
 */

import { dirname, join } from "path";
import { fileURLToPath } from "url";
import { mkdirSync, writeFileSync } from "fs";
import type { GenerateResult } from "@intentius/chant/codegen/generate";
import { loadSnapshot } from "../spec/snapshot";
import { assertPinnedSnapshot, assertSnapshotVersions } from "../spec/pin";
import { generateTypes, propertyDocs, type PropertyDoc } from "../spec/parse";
import { BUILTIN_SPECS } from "../spec/builtins";
import type { OtelSpecSnapshot } from "../spec/fetch";

export type { GenerateResult };

/** The packaged types entry re-exports the compiled declarations, which carry every config type. */
const TYPES_DTS = `// The otel lexicon's entity classes and config types are compiled to
// dist/index.d.ts (config types generated from upstream config.schema.yaml);
// this entry re-exports them.
export * from "../index";
`;

/** The upstream schema document behind each built-in, by class name, from the contrib index. */
export function builtinSchemaDocs(snapshot: OtelSpecSnapshot): Map<string, string> {
  const out = new Map<string, string>();
  const index = snapshot.distributions["otelcol-contrib"];
  for (const b of BUILTIN_SPECS) {
    const hit = index.find((c) => c.kind === b.kind && (c.type === b.type || c.deprecatedType === b.type));
    if (hit?.schema && snapshot.schemas[hit.schema]) out.set(b.className, hit.schema);
  }
  return out;
}

export interface OtelGenerated extends GenerateResult {
  /** Built-in class name → its property tree. */
  propertiesJSON: string;
}

export async function generate(opts?: { verbose?: boolean; force?: boolean }): Promise<OtelGenerated> {
  // The registry is derived from the classes, which import the generated
  // types; types are erased at runtime, so this import does not need them.
  const { BUILTIN_CATALOG, lexiconRegistry } = await import("../catalog");
  const snapshot = loadSnapshot();
  assertSnapshotVersions(snapshot.versions);
  assertPinnedSnapshot(snapshot);

  const roots = builtinSchemaDocs(snapshot);
  const generated = generateTypes(snapshot.schemas, [...new Set(roots.values())]);
  const aliases = [...roots]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([className, doc]) => `/** \`${className}\`'s config, from \`${doc}\`. */\nexport type ${className}SchemaConfig = ${generated.roots.get(doc)};\n`)
    .join("\n");

  const unresolved = [...generated.unresolved.keys()].sort();
  const indexTS = [
    "// Generated by `npm run generate` from src/spec/otel-schemas.snapshot.json. Do not edit.",
    `// Versions: ${Object.entries(snapshot.versions).map(([k, v]) => `${k} ${v}`).join(", ")}.`,
    ...(unresolved.length > 0
      ? ["// Upstream publishes no schema for these $refs, so they are typed `unknown`:", ...unresolved.map((u) => `//   ${u}`)]
      : []),
    "",
    'import type { Duration } from "../components/common";',
    "",
    generated.declarations,
    "// ── Built-in config types ──────────────────────────────────────────",
    "",
    aliases,
  ].join("\n");

  const properties: Record<string, Record<string, PropertyDoc>> = {};
  let propertyCount = 0;
  for (const [className, doc] of [...roots].sort(([a], [b]) => a.localeCompare(b))) {
    properties[className] = propertyDocs(snapshot.schemas, doc);
    propertyCount += Object.keys(properties[className]).length;
  }

  const registry = lexiconRegistry();
  if (opts?.verbose) {
    const components = BUILTIN_CATALOG.filter((c) => c.type !== undefined).length;
    console.error(
      `otel: ${components} built-in components, ${roots.size} typed from upstream config.schema.yaml ` +
        `(${snapshot.versions["otelcol-contrib"]}), plus Pipeline and Service (${BUILTIN_CATALOG.length} entities)`,
    );
    if (unresolved.length > 0) console.error(`otel: ${unresolved.length} upstream $refs have no schema and are typed unknown`);
  }
  return {
    lexiconJSON: `${JSON.stringify(registry, null, 2)}\n`,
    typesDTS: TYPES_DTS,
    indexTS,
    propertiesJSON: `${JSON.stringify(properties)}\n`,
    resources: BUILTIN_CATALOG.length,
    properties: propertyCount,
    enums: 0,
    warnings: [],
  };
}

/** Write the generated files to src/generated/. */
export function writeGeneratedFiles(result: OtelGenerated): void {
  const pkgDir = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
  const dir = join(pkgDir, "src", "generated");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "lexicon-otel.json"), result.lexiconJSON);
  writeFileSync(join(dir, "index.ts"), result.indexTS);
  writeFileSync(join(dir, "properties.json"), result.propertiesJSON);
}
