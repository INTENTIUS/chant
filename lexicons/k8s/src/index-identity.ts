/**
 * The k8s lexicon's identity rule for indexed objects (#4538, on #4523's
 * matcher, ../../../packages/core/src/lifecycle/identity-match.ts).
 *
 * core's Kubernetes lister (packages/core/src/cloud-lister/kubernetes.ts)
 * writes each object as:
 *
 * - `listedType` `<apiVersion>/<kind>` (`apps/v1/Deployment`, `v1/Secret`);
 * - `location` its namespace, or `cluster` for a cluster-scoped kind;
 * - `nativeId` `<namespace>/<name>`, or `<name>` for a cluster-scoped kind;
 * - one cloud id, `k8s-uid`, the object's `metadata.uid`.
 *
 * apiVersion, kind, namespace and name are all spelled by the user, so a
 * declaration that was never applied still matches its object by value.
 * The uid is assigned by the API server, so no declaration states it. It
 * still names an indexed node to the identity edge pass, where another
 * object's `ownerReferences[].uid` points at its owner.
 *
 * The match is by lexicon kind, not by listed type: discovery lists a
 * group at its preferred version, which need not be the version the
 * lexicon writes, and the kind is the same at any version. Coverage is
 * still read for the declared listed type, so a version the index did not
 * list reads not observed, never absent.
 *
 * What cannot match (`no-binding`):
 * - a name the declaration leaves out, spells with a reference, or asks the
 *   API server to generate (`metadata.generateName`);
 * - a namespaced kind with no `metadata.namespace`. The namespace kubectl
 *   or a GitOps controller would apply it to is not in the declaration.
 *
 * A type the lexicon has no API address for (`K8s::Sops::EncryptedSecretFile`,
 * a kind outside the generated surface) is `unsupported-kind`.
 */
import type { DeclaredIdentity, IndexIdentity } from "@intentius/chant/lifecycle/identity-match";
import type { NodeIdentityValue } from "@intentius/chant/graph-refs";
import type { IRNode } from "@intentius/chant/graph-ir";
import { operationFor, operationTable, type K8sOperationDescriptor, type K8sOperationTable } from "./api/operation-surface";
import { k8sListedTypeFor } from "./listed-types";

/** The location core's Kubernetes lister gives a cluster-scoped object. */
export const K8S_CLUSTER_LOCATION = "cluster";

/** The cloud id kind holding an object's `metadata.uid`. */
export const K8S_UID_CLOUD_ID = "k8s-uid";

function isRecord(v: unknown): v is Record<string, unknown> {
  return typeof v === "object" && v !== null && !Array.isArray(v);
}

const nonEmptyString = (v: unknown): v is string => typeof v === "string" && v !== "";

/**
 * The descriptor for `entityType` and whether its scope is known: from the
 * generated table when there is one, else derived (and the derived scope is
 * a guess, so it is not trusted for a declaration without a namespace).
 */
function addressOf(entityType: string, table: K8sOperationTable | undefined): { op: K8sOperationDescriptor; scopeKnown: boolean } | undefined {
  const t = table ?? operationTable();
  if (t[entityType]) return { op: t[entityType], scopeKnown: true };
  // Only the generated table knows CRDs and cluster-scoped kinds. A test table stands alone.
  if (table) return undefined;
  const derived = operationFor(entityType);
  return derived ? { op: derived, scopeKnown: false } : undefined;
}

/**
 * The identifier a k8s declaration spells for the index, or why it spells
 * none. `table` is the generated operation surface; a test passes one.
 */
export function k8sDeclaredIdentity(entityType: string, props: Record<string, unknown>, table?: K8sOperationTable): DeclaredIdentity {
  const address = addressOf(entityType, table);
  if (!address) {
    return { kind: "unmatchable", reason: "unsupported-kind", detail: `${entityType} has no Kubernetes API address on record` };
  }
  const { op, scopeKnown } = address;
  const metadata = isRecord(props.metadata) ? props.metadata : {};
  if (!nonEmptyString(metadata.name)) {
    const detail = nonEmptyString(metadata.generateName)
      ? `the name of ${entityType} is generated by the API server (metadata.generateName), so no declaration states it`
      : `identity is not in the declaration (${entityType} metadata.name)`;
    return { kind: "unmatchable", reason: "no-binding", detail };
  }
  const name = metadata.name;
  const apiVersion = nonEmptyString(props.apiVersion) ? props.apiVersion : op.apiVersion;
  const listedType = k8sListedTypeFor(apiVersion, op.kind);
  const namespace = nonEmptyString(metadata.namespace) ? metadata.namespace : undefined;

  if (scopeKnown && op.scope === "Cluster") {
    return { kind: "identifier", listedType, identifier: name, global: true, location: K8S_CLUSTER_LOCATION, entityKind: entityType };
  }
  if (!namespace) {
    return {
      kind: "unmatchable",
      reason: "no-binding",
      detail: scopeKnown
        ? `identity is not in the declaration (${entityType} ${name} names no metadata.namespace)`
        : `${entityType} ${name} names no metadata.namespace, and without a generated surface its scope is not known`,
    };
  }
  return { kind: "identifier", listedType, identifier: `${namespace}/${name}`, global: false, location: namespace, entityKind: entityType };
}

/** The values that name an indexed k8s object: its `<namespace>/<name>` and its uid. */
export function k8sNodeIdentities(node: IRNode): NodeIdentityValue[] {
  const out: NodeIdentityValue[] = [];
  if (node.nativeId) out.push({ kind: "native-id", value: node.nativeId });
  for (const c of node.facts?.cloudIds ?? []) if (c.kind === K8S_UID_CLOUD_ID) out.push({ kind: c.kind, value: c.value });
  return out;
}

export function createK8sIndexIdentity(table?: K8sOperationTable): IndexIdentity {
  return {
    substrate: "kubernetes",
    declaredIdentity: (entityType, props) => k8sDeclaredIdentity(entityType, props, table),
    nodeIdentities: k8sNodeIdentities,
  };
}

export const k8sIndexIdentity: IndexIdentity = createK8sIndexIdentity();
