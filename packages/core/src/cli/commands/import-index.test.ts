/**
 * #4524: `importFromIndex` end to end with a fake lexicon: it reads an index
 * file, writes the generator's files and the report, gives byte-identical
 * output for the same index and selection, and refuses an empty selection.
 * No project is built (the declared entities are passed in) and nothing
 * reaches a cloud.
 */
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "fs";
import { tmpdir } from "os";
import { join } from "path";
import { afterAll, describe, expect, test } from "vitest";
import { MASKED } from "../../deep-observation";
import type { LexiconPlugin } from "../../lexicon";
import { indexDocumentDigest, indexScopeKey, type CloudIndexScope, type IndexDocument } from "../../lifecycle/index-document";
import { importFromIndex, INDEX_IMPORT_REPORT_FILE } from "./import-index";

const dirs: string[] = [];
const scratch = () => {
  const d = mkdtempSync(join(tmpdir(), "chant-index-import-"));
  dirs.push(d);
  return d;
};
afterAll(() => {
  for (const d of dirs) rmSync(d, { recursive: true, force: true });
});

const SCOPE: CloudIndexScope = { kind: "cloud", substrate: "aws", scopeId: "111", locations: ["r1"], types: "*" };
const nodes = [
  { id: "aws/111/r1/Fake::Net/net-1", kind: "Fake::Net", lexicon: "fake", attrs: { Cidr: "10.0.0.0/16" }, listedType: "Fake::Net", location: "r1", nativeId: "net-1" },
  { id: "aws/111/r1/Fake::Db/db-1", kind: "Fake::Db", lexicon: "fake", attrs: { NetId: "net-1", Password: MASKED }, listedType: "Fake::Db", location: "r1", nativeId: "db-1" },
];
const edges = [{ from: nodes[1].id, to: nodes[0].id, kind: "ref" as const, origin: "derived" as const, rule: "fake:Fake::Db:NetId", viaAttr: "NetId" }];
const graph = { version: 1 as const, nodes, edges, groups: {} };
const DOC: IndexDocument = {
  index: "v1",
  stamp: { source: { kind: "cloud", name: "behold-lister" }, scope: SCOPE, scopeKey: indexScopeKey(SCOPE), observedAt: "2026-10-26T00:00:00.000Z", digest: indexDocumentDigest({ graph, coverage: [] }) },
  coverage: [],
  graph,
};

// The generator writes the IR as JSON, which is enough to see what it was given.
const plugin = {
  name: "fake",
  indexImport: {
    resource: (n: { kind: string; attrs: Record<string, unknown> }) => ({ type: n.kind, properties: n.attrs }),
    reference: (v: string, t: { logicalId: string; node: { nativeId?: string } }) => (v === t.node.nativeId ? { ref: t.logicalId } : undefined),
    secretParameter: (name: string) => ({ name, type: "String" }),
    parameterReference: (name: string) => ({ param: name }),
  },
  templateGenerator: () => ({
    ownsLayout: true,
    generate: (ir: unknown) => [{ path: "main.ts", content: `export const ir = ${JSON.stringify(ir, null, 2)};\n` }],
  }),
} as unknown as LexiconPlugin;

function indexFile(): string {
  const p = join(scratch(), "index.json");
  writeFileSync(p, JSON.stringify(DOC));
  return p;
}

describe("importFromIndex", () => {
  test("writes the generator's files with the header, and the report beside them", async () => {
    const out = join(scratch(), "out");
    const result = await importFromIndex({ index: indexFile(), selection: { all: true }, output: out, plugins: [plugin], declaredEntities: new Map() });
    expect(result.success).toBe(true);
    expect(readdirSync(out).sort()).toEqual([INDEX_IMPORT_REPORT_FILE, "main.ts"]);
    const main = readFileSync(join(out, "main.ts"), "utf-8");
    expect(main.startsWith("// Generated by chant import --index. Nothing was applied.")).toBe(true);
    expect(main).not.toContain(MASKED);
    expect(main).toContain('"ref": "Net1"');
    const report = JSON.parse(readFileSync(join(out, INDEX_IMPORT_REPORT_FILE), "utf-8"));
    expect(report.report).toBe("chant-index-import/v1");
    expect(report.resources.map((r: { status: string }) => r.status)).toEqual(["imported", "imported"]);
    expect(report.parameters).toEqual([{ name: "Db1Password", node: nodes[1].id, path: "Password", group: "" }]);
  });

  test("the same index and selection give byte-identical files", async () => {
    const index = indexFile();
    const a = join(scratch(), "a");
    const b = join(scratch(), "b");
    await importFromIndex({ index, selection: { all: true }, output: a, plugins: [plugin], declaredEntities: new Map() });
    await importFromIndex({ index, selection: { all: true }, output: b, plugins: [plugin], declaredEntities: new Map() });
    for (const f of ["main.ts", INDEX_IMPORT_REPORT_FILE]) {
      expect(readFileSync(join(b, f), "utf-8")).toBe(readFileSync(join(a, f), "utf-8"));
    }
  });

  test("an empty selection is refused before the index is read", async () => {
    const result = await importFromIndex({ index: "does-not-exist", selection: {}, output: join(scratch(), "o"), plugins: [plugin] });
    expect(result.success).toBe(false);
    expect(result.error).toMatch(/name what to import/);
  });

  test("a file that is not an index is refused", async () => {
    const p = join(scratch(), "not-index.json");
    writeFileSync(p, JSON.stringify({ hello: 1 }));
    const result = await importFromIndex({ index: p, selection: { all: true }, output: join(scratch(), "o"), plugins: [plugin], declaredEntities: new Map() });
    expect(result.success).toBe(false);
    expect(result.error).toMatch(/does not hold index documents/);
  });
});
