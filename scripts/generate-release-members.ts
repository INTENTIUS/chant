/**
 * Writes one release member per publishable npm package under `release/`
 * (#5133, #5132 decision 1), and the nested `release/chant.workspace.json`
 * that declares them.
 *
 * A package is publishable when its `package.json` under `packages/` or
 * `lexicons/` is not private. Each
 * member takes the name of the outer member that owns the package's
 * directory (`core`, `k8s-client`, `lexicon-aws`, ...) and holds:
 *
 * - `chant.config.ts`: one `npm` target for the package's tarball;
 * - `packages.component.ts`: the component a cut needs to compile.
 *
 * The nested declaration lists the members in dependency layers, core
 * first, repeats chant's `ci.green` so a cut from a
 * member reads the same green rule as the root, and names every member file
 * as a `generated` entry, so a stale file fails `chant workspace check
 * --generated`. The outer declaration names the nested one the same way.
 *
 *   npx tsx scripts/generate-release-members.ts           write everything
 *   npx tsx scripts/generate-release-members.ts --file <path> -o <out>
 *                                                          write one file, <path> relative to release/
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const RELEASE = join(ROOT, "release");
const SELF = "scripts/generate-release-members.ts";

export interface ReleasePackage {
  /** The package directory, relative to the repo root: `lexicons/aws`. */
  dir: string;
  /** The npm name: `@intentius/chant-lexicon-aws`. */
  name: string;
  /** The outer member owning `dir`, and the release member's name: `lexicon-aws`. */
  member: string;
  /** Publishable workspace directories this package depends on, peers and optionals included. */
  needs: string[];
}

interface PackageJson {
  name: string;
  private?: boolean;
  dependencies?: Record<string, string>;
  peerDependencies?: Record<string, string>;
  optionalDependencies?: Record<string, string>;
}

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(path, "utf-8")) as T;
}

/** Every publishable package, in dependency layer order: Kahn layers, alphabetical by directory within a layer. */
export function releasePackages(root = ROOT): ReleasePackage[] {
  const outer = readJson<{ members: { name: string; dir?: string }[] }>(join(root, "chant.workspace.json"));
  const pkgs = new Map<string, PackageJson>();
  for (const base of ["packages", "lexicons"]) {
    for (const d of readdirSync(join(root, base)).sort()) {
      const file = join(root, base, d, "package.json");
      if (!existsSync(file)) continue;
      const pkg = readJson<PackageJson>(file);
      if (!pkg.private) pkgs.set(`${base}/${d}`, pkg);
    }
  }
  const owner = new Map([...pkgs].map(([dir, p]) => [p.name, dir]));
  const all: ReleasePackage[] = [];
  for (const [dir, p] of pkgs) {
    const member = outer.members.find((m) => m.dir === dir)?.name;
    if (!member) throw new Error(`${dir} is published to npm and no member of chant.workspace.json owns it; declare it there first`);
    const deps = Object.keys({ ...p.dependencies, ...p.peerDependencies, ...p.optionalDependencies });
    const needs = [...new Set(deps.map((n) => owner.get(n)).filter((x): x is string => x !== undefined && x !== dir))].sort();
    all.push({ dir, name: p.name, member, needs });
  }
  const out: ReleasePackage[] = [];
  const left = new Map(all.map((p) => [p.dir, p]));
  while (left.size > 0) {
    const ready = [...left.values()].filter((p) => !p.needs.some((n) => left.has(n))).sort((a, b) => (a.dir < b.dir ? -1 : 1));
    if (ready.length === 0) throw new Error(`a dependency cycle among ${[...left.keys()].join(", ")}`);
    for (const p of ready) {
      out.push(p);
      left.delete(p.dir);
    }
  }
  return out;
}

const HEADER = `// Generated by ${SELF}; edit the generator, not this file.\n`;

/**
 * A member's config is an object literal rather than a call to a shared
 * factory: `chant workspace check` and `workspace status` read
 * `environments` statically, and an exported call can't be read without
 * running it (WSP073). The generator is the one place the shape lives.
 */
export function memberConfig(p: ReleasePackage): string {
  // #5154: a lexicon's single-package releases before the train were tagged lexicon-<n>-v<v>.
  const legacy = p.dir.startsWith("lexicons/") ? `\n    legacyTags: ["${p.member}-v"],` : "";
  return `${HEADER}import type { ChantConfig } from "@intentius/chant";

// ${p.name}'s release member (#5132). It releases ${p.dir} at its own label,
// as one member of chant's release train (release.train in
// ../chant.config.ts, #5154). \`chant workspace train prepare\` stamps the
// label into its package.json and each @intentius/* range with the label the
// train gives that package (ranges: "train"); npm packs the directory, which
// runs its prepack, when the train publishes it. stage: false publishes
// straight to latest, since moving a dist-tag over trusted publishing needs a
// per-package setting chant's records do not have (#3904). tokenEnv keeps
// the fallback to NPM_TOKEN.
export default {
  environments: ["npm"],
  release: {${legacy}
    version: { packages: ["../../${p.dir}"], lockfile: false, ranges: "train" },
    publish: [
      {
        type: "npm",
        access: "public",
        stage: false,
        tokenEnv: "NPM_TOKEN",
        packages: ["../../${p.dir}"],
      },
    ],
  },
} satisfies ChantConfig;
`;
}

export function memberComponent(): string {
  return `${HEADER}// The package ships through release.publish in chant.config.ts, so this\n// component deploys nothing. A cut needs one component to compile (#4040).\nexport const packages = { name: "packages", dependsOn: [], deploy: [] };\n`;
}

const MEMBER_FILES = ["chant.config.ts", "packages.component.ts"] as const;

export function nestedDeclaration(pkgs: ReleasePackage[], root = ROOT): string {
  const outer = readJson<{ ci?: { green?: unknown } }>(join(root, "chant.workspace.json"));
  const decl = {
    name: "npm",
    schema: 1,
    ...(outer.ci?.green ? { ci: { green: outer.ci.green } } : {}),
    members: pkgs.map((p) => ({
      name: p.member,
      dir: p.member,
      kind: "chant",
      generated: MEMBER_FILES.map((f) => ({
        path: f,
        // A source must sit inside this workspace; the generator is the outer
        // declaration's source of release/chant.workspace.json instead.
        generator: `npx tsx ../../${SELF} --file ${p.member}/${f} -o ${f}`,
      })),
    })),
  };
  return `${JSON.stringify(decl, null, 2)}\n`;
}

/** Every file the generator owns, keyed by its path relative to `release/`. */
export function releaseMemberFiles(root = ROOT): Map<string, string> {
  const pkgs = releasePackages(root);
  const files = new Map<string, string>([["chant.workspace.json", nestedDeclaration(pkgs, root)]]);
  for (const p of pkgs) {
    files.set(`${p.member}/chant.config.ts`, memberConfig(p));
    files.set(`${p.member}/packages.component.ts`, memberComponent());
  }
  return files;
}

function main(argv: string[]): void {
  const files = releaseMemberFiles();
  const at = argv.indexOf("--file");
  if (at >= 0) {
    const path = argv[at + 1];
    const o = argv.findIndex((a) => a === "-o" || a === "--output");
    const content = path === undefined ? undefined : files.get(path);
    if (content === undefined) throw new Error(`no generated release file ${path ?? "(missing)"}; the files are ${[...files.keys()].join(", ")}`);
    const out = o >= 0 && argv[o + 1] ? resolve(argv[o + 1]) : join(RELEASE, path!);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, content);
    return;
  }
  for (const [path, content] of files) {
    const out = join(RELEASE, path);
    mkdirSync(dirname(out), { recursive: true });
    if (!existsSync(out) || readFileSync(out, "utf-8") !== content) {
      writeFileSync(out, content);
      console.log(`wrote release/${path}`);
    }
  }
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) main(process.argv.slice(2));
